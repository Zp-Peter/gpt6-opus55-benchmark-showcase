// 方位角（度）：入场与踩踏时缓慢转到更侧面的角度，便于看清抬腿与落脚；甩尾前缓慢转回
const AZ = new Track([[0, 34], [5, 32], [12, 14], [16, 8], [23.5, 8], [29, 28], [32.5, 34], [48, 34], [62, 38]]);

export const choreo = {
  root(t) { return { x: rootX.at(t), z: rootZ.at(t), h: rootH.at(t) }; },
  params(t) {
    const o = {};
    for (const k in P) o[k] = P[k].at(t);
    return o;
  },
  footScript(side, t) {
    const S = STOMP;
    if (side !== S.side || t < S.t0 || t > S.tEnd) return null;
    return {
      landed: t >= S.tSlam,
      apply(f, hf) {
        if (!f.stompFrom || f.stompStart !== S.t0) { f.stompFrom = f.pos.clone(); f.stompYaw0 = f.yaw; f.stompStart = S.t0; }
        const tgt = S.target.clone(); tgt.y = hf.baseAt(tgt.x, tgt.z) + 3; // 压扁后的地面上
        if (t < S.tRaise) { // 抬腿：先上后前
          const u = (t - S.t0) / (S.tRaise - S.t0);
          const e = u * u * (3 - 2 * u);
          const exz = u * u; // 先抬高、后前移，避免刮到店面招牌
          f.pos.lerpVectors(f.stompFrom, S.raise, exz);
          f.pos.y = f.stompFrom.y + (S.raise.y - f.stompFrom.y) * Math.sin(Math.min(1, u * 1.3) * Math.PI / 2);
          f.yaw = f.stompYaw0 + (S.yaw - f.stompYaw0) * e;
          f.pitch = -0.7 * Math.sin(Math.min(1, u * 1.3) * Math.PI / 2);
          f.phi = 1.13 - 0.13 * e;
        } else if (t < S.tHold) { // 悬停蓄力（轻微颤动）
          const w = Math.sin((t - S.tRaise) * 38) * 0.25;
          f.pos.copy(S.raise); f.pos.y += w + (t - S.tRaise) * 1.2;
          f.pitch = -0.7; f.phi = 1.0; f.yaw = S.yaw;
        } else if (t < S.tSlam) { // 重踩：加速下落
          const u = (t - S.tHold) / (S.tSlam - S.tHold);
          const e = u * u * u;
          const from = S.raise.clone(); from.y += (S.tHold - S.tRaise) * 1.2;
          f.pos.lerpVectors(from, tgt, e);
          f.pitch = -0.7 * (1 - e); f.phi = 1.0 + 0.13 * e; f.yaw = S.yaw;
        } else { // 踩实并保持
          f.pos.copy(tgt); f.pitch = 0; f.phi = 1.13; f.yaw = S.yaw;
        }
      },
    };
  },
  camera(t) { return { x: camT[0].at(t), z: camT[1].at(t), zoom: camT[2].at(t), az: AZ.at(t) }; },
  phase(t) { let p = PHASES[0]; for (const ph of PHASES) if (t >= ph.t) p = ph; return p; },
};

